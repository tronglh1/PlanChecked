// Generates 01_codes.sql, 02_text_templates.sql, 03_plants.sql from data/*.mjs.  Usage: node supabase/seed/build.mjs
// Output is idempotent (upserts) so it can be re-run on an existing database.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { reasons, milestones, tags, hints, safety, tasks, problems } from './data/codes.mjs';
import { plants, expandPlant } from './data/plants.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const q = (s) => (s === null || s === undefined ? 'null' : `'${String(s).replace(/'/g, "''")}'`);
const arr = (a) => (a.length ? `array[${a.map(q).join(',')}]::text[]` : `'{}'::text[]`);
const HEADER = '-- GENERATED by supabase/seed/build.mjs from supabase/seed/data/*.mjs. Do not edit by hand.\n';

// Safety check shared with the test-suite: no dose / amount / concentration in any text.
export const DOSE_RE = /\d\s*(ml|mg|g|kg|l|lít|%|ppm|muỗng|thìa|tsp|tbsp|gram)(?![a-zà-ỹ])/i;

// ------------------------------------------------------------ 01_codes
let s = HEADER;
s += 'insert into public.reason_codes(code) values\n' + Object.keys(reasons).map((c) => `  (${q(c)})`).join(',\n') + '\non conflict do nothing;\n\n';
s += 'insert into public.milestone_codes(code, sort_order) values\n' + milestones.map(([c, o]) => `  (${q(c)}, ${o})`).join(',\n') +
  '\non conflict (code) do update set sort_order = excluded.sort_order;\n\n';
s += 'insert into public.task_codes(code, "group", default_window, default_frequency, default_interval_days, safety_flags) values\n' +
  tasks.map((t) => `  (${q(t.code)}, ${q(t.group)}, ${q(t.window)}, ${q(t.frequency)}, ${t.interval ?? 'null'}, ${arr(t.flags)})`).join(',\n') +
  '\non conflict (code) do update set "group" = excluded."group", default_window = excluded.default_window,\n' +
  '  default_frequency = excluded.default_frequency, default_interval_days = excluded.default_interval_days, safety_flags = excluded.safety_flags;\n\n';
s += 'insert into public.problem_codes(code, symptoms, causes, safe_actions, severity) values\n' +
  problems.map((p) => `  (${q(p.code)}, ${arr(p.symptoms)}, ${arr(p.causes)}, ${arr(p.actions)}, ${p.sev})`).join(',\n') +
  '\non conflict (code) do update set symptoms = excluded.symptoms, causes = excluded.causes,\n' +
  '  safe_actions = excluded.safe_actions, severity = excluded.severity;\n';
writeFileSync(join(here, '01_codes.sql'), s);

// ------------------------------------------------------------ 02_text_templates
const rows = [];
const add = (kind, code, lang, field, body) => rows.push([kind, code, lang, field, body]);
for (const t of tasks) for (const lang of ['vi', 'en']) {
  add('task', t.code, lang, 'name', t[lang].name);
  add('task', t.code, lang, 'steps', t[lang].steps.join('\n'));
  add('task', t.code, lang, 'why', t[lang].why);
  if (t.flags.length) add('task', t.code, lang, 'safety', t.flags.map((f) => safety[f][lang]).join('\n'));
}
for (const p of problems) for (const lang of ['vi', 'en']) {
  add('problem', p.code, lang, 'name', p[lang].name);
  add('problem', p.code, lang, 'steps', p[lang].steps.join('\n'));
  add('problem', p.code, lang, 'why', p[lang].why);
  add('problem', p.code, lang, 'safety', `${safety.organic_first[lang]}\n${safety.label_required[lang]}`);
}
for (const [code, r] of Object.entries(reasons)) for (const lang of ['vi', 'en']) {
  add('reason', code, lang, 'name', r[lang][0]);
  add('reason', code, lang, 'why', r[lang][1]);
}
for (const [code, , vi, en] of milestones) {
  add('milestone', code, 'vi', 'name', vi[0]); add('milestone', code, 'vi', 'why', vi[1]);
  add('milestone', code, 'en', 'name', en[0]); add('milestone', code, 'en', 'why', en[1]);
}
for (const [code, [vi, en]] of Object.entries(tags)) { add('tag', code, 'vi', 'name', vi); add('tag', code, 'en', 'name', en); }
for (const [code, h] of Object.entries(hints)) for (const lang of ['vi', 'en']) {
  add('hint', code, lang, 'name', h[lang][0]);
  add('hint', code, lang, 'steps', h[lang][1]);
}
for (const [code, m] of Object.entries(safety)) for (const lang of ['vi', 'en']) add('safety', code, lang, 'safety', m[lang]);

for (const [kind, code, lang, field, body] of rows) {
  if (DOSE_RE.test(body)) throw new Error(`dose-like text in ${kind}/${code}/${lang}/${field}: ${body}`);
}
s = HEADER + 'insert into public.text_templates(kind, code, lang, field, body, source_ref, status) values\n' +
  rows.map(([k, c, l, f, b]) => `  (${q(k)}, ${q(c)}, ${q(l)}, ${q(f)}, ${q(b)}, 'seed:v1', 'ai_unverified')`).join(',\n') +
  '\non conflict (kind, code, lang, field) do update set body = excluded.body, source_ref = excluded.source_ref, status = excluded.status;\n';
writeFileSync(join(here, '02_text_templates.sql'), s);

// ------------------------------------------------------------ 03_plants
s = HEADER;
const ids = plants.map((p) => q(p.id)).join(',');
s += 'insert into public.plants(id, "group", name_vi, name_en, scientific_name, search_key, difficulty, days_to_harvest, toxic_child, toxic_pet, hidden, data_status, sources) values\n' +
  plants.map((p) => `  (${q(p.id)}, ${q(p.group)}, ${q(p.vi)}, ${q(p.en)}, ${q(p.sci)}, public.vn_search_key(${q(`${p.vi} ${p.en} ${p.aliases}`)}), ${q(p.difficulty)}, ${p.days}, ${p.tc}, ${p.tp}, ${p.id.startsWith('generic_')}, 'ai_unverified', array['seed:v1'])`).join(',\n') +
  '\non conflict (id) do update set "group" = excluded."group", name_vi = excluded.name_vi, name_en = excluded.name_en,\n' +
  '  scientific_name = excluded.scientific_name, search_key = excluded.search_key, difficulty = excluded.difficulty,\n' +
  '  days_to_harvest = excluded.days_to_harvest, toxic_child = excluded.toxic_child, toxic_pet = excluded.toxic_pet,\n' +
  '  hidden = excluded.hidden, sources = excluded.sources;\n\n';
s += `delete from public.plant_stages where plant_id in (${ids});  -- cascades plant_default_tasks\n`;
s += `delete from public.plant_problems where plant_id in (${ids});\n\n`;

const stageRows = [], taskRows = [], probRows = [];
for (const pl of plants) {
  const x = expandPlant(pl);
  for (const st of x.stages) stageRows.push(`  (${q(pl.id)}, ${q(st.code)}, ${st.order}, ${q(st.vi)}, ${q(st.en)}, ${st.min}, ${st.max}, ${q(st.milestone)}, ${q(st.phase)})`);
  for (const t of x.tasks) taskRows.push(`  (${q(pl.id)}, ${q(t.stage)}, ${q(t.task)}, ${q(t.window)}, ${t.every}, ${t.offset}, ${q(t.reason)})`);
  x.problems.forEach((c, i) => probRows.push(`  (${q(pl.id)}, ${q(c)}, ${i + 1})`));
}
s += 'insert into public.plant_stages(plant_id, code, "order", name_vi, name_en, day_min, day_max, milestone_code, phase) values\n' + stageRows.join(',\n') + ';\n\n';
s += 'insert into public.plant_default_tasks(plant_id, stage_code, task_code, "window", every_d, offset_d, reason_code) values\n' + taskRows.join(',\n') + ';\n\n';
s += 'insert into public.plant_problems(plant_id, problem_code, rank) values\n' + probRows.join(',\n') + ';\n';
writeFileSync(join(here, '03_plants.sql'), s);

console.log(`seed written: ${tasks.length} task codes, ${problems.length} problem codes, ${Object.keys(reasons).length} reasons, ${rows.length} text rows, ${plants.length} plants, ${taskRows.length} default tasks`);
